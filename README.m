# SignTalk 2.5 Pro Max

**Two-Way Sign Language Translator** built with **Gemini 2.5 Flash**  
**Submitted to Gemini Live Agent Challenge**

## 📌 About the Project
SignTalk is a real-time two-way translator that converts:
- **Sign Language** (via DroidCam) → Speech + Text
- **Speech or Text** → Local sign language video

## 🚀 Current Features
- Real-time sign language recognition using Gemini
- Text-to-sign and Speech-to-sign with local videos
- Clean, responsive Streamlit interface
- Secure API key management using `.env`
- History log of all translations

## 🛠️ Technologies Used
- Streamlit
- Google Gemini 2.5 Flash
- OpenCV
- gTTS
- python-dotenv

